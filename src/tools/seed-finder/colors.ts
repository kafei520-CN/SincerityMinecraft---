/** 生物群系地图色。变种用略浅的底色。 */
export function biomeColor(id: number): string {
  if (NAMED[id]) {
    return NAMED[id];
  }
  const base = id > 128 ? id - 128 : id;
  const known = NAMED[base];
  if (known) {
    return known;
  }
  const hue = (id * 47) % 360;
  return `hsl(${hue} 35% 42%)`;
}
